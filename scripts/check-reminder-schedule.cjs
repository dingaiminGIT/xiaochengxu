const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const ctx = { loadStore: () => ({}), saveStore() {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('utils/reminders.js', 'utf8').replace(/^import .*;$/gm, '').replace(/export /g, '') + '\nthis.resolve = resolveReminderTime;', ctx);
const resolve = ctx.resolve;
const at = (day, hour, minute = 0) => new Date(2026, 9, day, hour, minute).getTime();
const now = at(28, 10); // Wednesday
assert.equal(resolve({ repeat: 'daily', time: '11:00', date: '2020-01-01' }, now), at(28, 11));
assert.equal(resolve({ repeat: 'daily', time: '09:00' }, now), at(29, 9));
assert.equal(resolve({ repeat: 'daily', time: '10:00' }, now), at(29, 10));
assert.equal(resolve({ repeat: 'weekly', weekday: 3, time: '11:00' }, now), at(28, 11));
assert.equal(resolve({ repeat: 'weekly', weekday: 3, time: '09:00' }, now), new Date(2026, 10, 4, 9).getTime());
assert.equal(resolve({ repeat: 'weekly', weekday: 0, time: '09:00' }, now), new Date(2026, 10, 1, 9).getTime());
assert.throws(() => resolve({ repeat: 'weekly', weekday: -1, time: '09:00' }, now), /星期/);
assert.throws(() => resolve({ repeat: 'daily', time: '25:00' }, now), /无效/);
assert.throws(() => resolve({ repeat: 'none', time: '09:00' }, now), /日期/);
const previous = { repeat: 'weekly', dueAt: at(21, 9) };
assert.equal(resolve({ repeat: 'weekly', weekday: 3, time: '09:00' }, now, previous), previous.dueAt, 'note-only editing preserves overdue occurrence');
assert.equal(resolve({ repeat: 'weekly', weekday: 4, time: '09:00' }, now, previous), at(29, 9));
assert.equal(resolve({ repeat: 'none', date: '2026-10-31', time: '09:00' }, now), at(31, 9));
let page;
vm.runInContext(fs.readFileSync('pages/pet-space/reminder-edit.js', 'utf8').replace(/import[\s\S]*?from\s+['"][^'"]+['"];?/g, ''), Object.assign(ctx, { Page: p => { page = p; } }));
page.data = { ...page.data };
page.setData = patch => Object.assign(page.data, patch);
page.repeat({ detail: { value: '1' } }); assert.equal(page.data.repeatId, 'daily');
page.repeat({ detail: { value: '2' } }); assert.equal(page.data.repeatId, 'weekly');
page.weekday({ detail: { value: '6' } }); assert.equal(page.data.weekdayIndex, 6);
page.repeat({ detail: { value: '0' } }); assert.equal(page.data.repeatId, 'none');
console.log('PASS: daily/weekly scheduling, Sunday and month rollover, missing weekday, invalid time, unchanged edit, and repeat switching');
